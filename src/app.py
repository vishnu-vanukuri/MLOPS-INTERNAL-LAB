@app.get("/health", response_model=HealthResponse, tags=["Monitoring"])
def health():
    """
    Health check endpoint: verifies service status, model availability, and uptime.
    """
    uptime = time.time() - START_TIME
    REQUEST_COUNT.labels(endpoint="/health", method="GET", status="200").inc()
    return HealthResponse(
        status="healthy" if model_pipeline is not None else "degraded",
        service="online-payment-fraud-detection",
        version="1.0.0",
        uptime_seconds=round(uptime, 2),
        model_loaded=(model_pipeline is not None),
        timestamp=datetime.now(timezone.utc).isoformat(),
    )


@app.get("/metrics", tags=["Monitoring"])
def get_metrics():
    """
    Prometheus metrics scraping endpoint.
    """
    REQUEST_COUNT.labels(endpoint="/metrics", method="GET", status="200").inc()
    return Response(content=generate_latest(), media_type=CONTENT_TYPE_LATEST)


