@app.post("/predict", response_model=PredictionResponse, tags=["Inference"])
@app.post("/predict/", response_model=PredictionResponse, tags=["Inference"])
def predict_transaction(txn: TransactionInput):
    """
    Real-time fraud scoring for an incoming payment transaction.
    """
    start_time = time.time()
    txn_id = txn.Transaction_ID or f"TXN_{int(time.time()*1000)}"

    # Record incoming amount and risk signal metrics
    AMOUNT_HISTOGRAM.observe(txn.Transaction_Amount_INR)
    RISK_SIGNAL_HISTOGRAM.observe(txn.Fraud_Risk_Signal)

    logger.info(
        f"Incoming Request | TXN_ID: {txn_id} | Amount: INR {txn.Transaction_Amount_INR:.2f} | "
        f"Method: {txn.Payment_Method} | Channel: {txn.Transaction_Channel} | "
        f"Device: {txn.Device_Status} | Location: {txn.Location_Type} | Signal: {txn.Fraud_Risk_Signal}"
    )

    if model_pipeline is None:
        ERROR_COUNT.labels(endpoint="/predict", error_type="ModelNotLoaded").inc()
        REQUEST_COUNT.labels(endpoint="/predict", method="POST", status="503").inc()
        logger.error(f"Prediction failed for {txn_id}: Model pipeline is not loaded.")
        raise HTTPException(
            status_code=status.HTTP_53_SERVICE_UNAVAILABLE,
            detail="Fraud classification model is not loaded.",
        )

    try:
        # Build DataFrame for inference
        input_data = {
            "Transaction_Amount_INR": [txn.Transaction_Amount_INR],
            "Transaction_Hour": [txn.Transaction_Hour],
            "Payment_Method": [txn.Payment_Method],
            "Transaction_Channel": [txn.Transaction_Channel],
            "Device_Status": [txn.Device_Status],
            "Location_Type": [txn.Location_Type],
            "Transactions_Last_Hour": [txn.Transactions_Last_Hour],
            "Account_Age_Days": [txn.Account_Age_Days],
            "Fraud_Risk_Signal": [txn.Fraud_Risk_Signal],
            "Failed_OTP_Attempts": [txn.Failed_OTP_Attempts],
            "Previous_Disputes": [txn.Previous_Disputes],
            "Minutes_Since_Last_Transaction": [txn.Minutes_Since_Last_Transaction],
        }
        df_input = pd.DataFrame(input_data)

        # Run model inference with latency measurement
        with LATENCY_HISTOGRAM.time():
            prob_fraud = float(model_pipeline.predict_proba(df_input)[0, 1])

        # Classification decision based on calibrated operational threshold
        is_fraud = prob_fraud >= DECISION_THRESHOLD
        pred_label = "Fraudulent" if is_fraud else "Legitimate"
        risk_tier = compute_risk_tier(prob_fraud)
        risk_score = round(prob_fraud * 100.0, 2)

        duration_ms = (time.time() - start_time) * 1000.0

        # Update Prometheus metrics
        PREDICTION_COUNT.labels(prediction=pred_label, risk_tier=risk_tier).inc()
        LAST_FRAUD_PROBABILITY.set(prob_fraud)
        REQUEST_COUNT.labels(endpoint="/predict", method="POST", status="200").inc()

        # Log prediction result
        logger.info(
            f"Prediction Result | TXN_ID: {txn_id} | Label: {pred_label} | "
            f"Probability: {prob_fraud:.4f} | Risk Score: {risk_score} ({risk_tier}) | "
            f"Latency: {duration_ms:.2f}ms"
        )

        return PredictionResponse(
            transaction_id=txn_id,
            prediction=pred_label,
            fraud_probability=round(prob_fraud, 4),
            risk_score=risk_score,
            risk_tier=risk_tier,
            decision_threshold=DECISION_THRESHOLD,
            processing_time_ms=round(duration_ms, 2),
            timestamp=datetime.now(timezone.utc).isoformat(),
            status="SUCCESS",
        )

    except Exception as e:
        ERROR_COUNT.labels(endpoint="/predict", error_type=type(e).__name__).inc()
        REQUEST_COUNT.labels(endpoint="/predict", method="POST", status="500").inc()
        logger.error(
            f"Error during fraud prediction for TXN_ID: {txn_id} - Error: {str(e)}",
            exc_info=True,
        )
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Inference error: {str(e)}",
        )


@app.post("/predict/batch", response_model=List[PredictionResponse], tags=["Inference"])
def predict_batch(transactions: List[TransactionInput]):
    """
    Batch fraud scoring endpoint for evaluating transaction streams.
    """
    results = []
    for txn in transactions:
        res = predict_transaction(txn)
        results.append(res)
    return results


